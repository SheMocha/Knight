function toRoman(num: number): string {
  const pairs: [number, string][] = [
    [50, 'L'],
    [40, 'XL'],
    [10, 'X'],
    [9, 'IX'],
    [5, 'V'],
    [4, 'IV'],
    [1, 'I'],
  ];
  let n = num;
  let out = '';
  for (const [val, sym] of pairs) {
    while (n >= val) {
      out += sym;
      n -= val;
    }
  }
  return out;
}

function buildAllLevels(): LevelConfig[] {
  const list: LevelConfig[] = [];

  for (let wIdx = 0; wIdx < WORLDS.length; wIdx++) {
    const world = WORLDS[wIdx];
    const specs = WORLD_STAGE_SPECS[world.id];
    const vis = THEME_VISUALS[world.theme];

    for (let sIdx = 0; sIdx < LEVELS_PER_WORLD; sIdx++) {
      const id = wIdx * LEVELS_PER_WORLD + sIdx + 1;
      const spec = specs[sIdx];
      const progress = (id - 1) / (TOTAL_LEVELS - 1); // 0..1
      const isBossLevel = Boolean(spec.boss);

      const timeLimit = isBossLevel
        ? Math.min(115, 75 + Math.floor(wIdx * 4))
        : Math.min(72, 46 + Math.floor(wIdx * 2.2) + (sIdx >= 4 ? 4 : 0));

      const scrollSpeed = Number((6.6 + progress * 3.8 + sIdx * 0.14).toFixed(2));
      const spawnInterval = Number(Math.max(0.68, 1.24 - progress * 0.42 - sIdx * 0.015).toFixed(2));

      // Cadı olasılığı: Karanlık Orman ve Lanetli Mezarlıkta biraz daha yüksek, ilk bölümde nazik
      const themeWitchBonus =
        world.theme === 'forest' ? 0.08 : world.theme === 'graveyard' ? 0.07 : world.theme === 'dragon' ? 0.05 : 0;
      const witchChance = isBossLevel
        ? 0
        : Number(Math.min(0.26, 0.07 + progress * 0.11 + themeWitchBonus).toFixed(2));

      const specialObjectChance = isBossLevel
        ? 0
        : Number(Math.min(0.46, 0.24 + progress * 0.14 + (spec.spawnPattern === 'treasure_run' ? 0.08 : 0)).toFixed(2));

      const specialNpcChance = isBossLevel
        ? 0
        : Number(Math.min(0.24, 0.11 + progress * 0.08 + (sIdx === 0 && world.id === 1 ? -0.04 : 0)).toFixed(2));

      // Merkezi kalibrasyon: bölüm hedefi, gerçek maksimum skor sınırı ve yoğunluk ölçeği
      const { scoreTarget, maxScore, levelScoreScale } = computeLevelScoreCalibration({
        id,
        totalLevels: TOTAL_LEVELS,
        timeLimit,
        spawnInterval,
        witchChance,
        specialObjectChance,
        specialNpcChance,
        spawnPattern: spec.spawnPattern,
        levelEvent: spec.levelEvent,
        objectPool: spec.objectPool,
        specialObjectPool: spec.specialObjectPool,
        characterPool: spec.characterPool,
        specialNpcPool: spec.specialNpcPool,
        isBossLevel,
        boss: spec.boss,
      });

      // Merkezi altın ekonomisi kalibrasyonu: 60 bölüm boyunca dengeli geçici altın + tamamlama bonusu
      const {
        levelGoldScale,
        expectedLevelGold,
        maxInLevelGold,
        completionBonusGold,
      } = computeLevelGoldCalibration({
        id,
        totalLevels: TOTAL_LEVELS,
        timeLimit,
        spawnInterval,
        witchChance,
        specialObjectChance,
        specialNpcChance,
        spawnPattern: spec.spawnPattern,
        levelEvent: spec.levelEvent,
        objectPool: spec.objectPool,
        specialObjectPool: spec.specialObjectPool,
        characterPool: spec.characterPool,
        specialNpcPool: spec.specialNpcPool,
        isBossLevel,
        boss: spec.boss,
      });

      list.push({
        id,
        worldId: world.id,
        levelInWorld: sIdx + 1,
        roman: toRoman(id),
        name: spec.name,
        subtitle: spec.subtitle,
        atmosphere: spec.atmosphere,
        lockedMystery: spec.lockedMystery,
        artwork: world.artwork,
        fallbackGradient: world.fallbackGradient,
        theme: world.theme,
        bgVariant: sIdx,
        lightingTint: spec.lightingTint,
        difficulty: Math.min(10, Math.max(1, world.id)),
        scoreTarget,
        maxScore,
        levelScoreScale,
        timeLimit,
        scrollSpeed,
        goldScale: levelGoldScale,
        expectedLevelGold,
        maxInLevelGold,
        completionBonusGold,
        spawnInterval,
        witchChance,
        specialObjectChance,
        specialNpcChance,
        spawnPattern: spec.spawnPattern,
        levelEvent: spec.levelEvent,
        skyTop: vis.skyTop,
        skyMid: vis.skyMid,
        skyBottom: vis.skyBottom,
        sunColor: vis.sunColor,
        fogColor: vis.fogColor,
        hillColorFar: vis.hillColorFar,
        hillColorMid: vis.hillColorMid,
        roadTint: vis.roadTint,
        hasMoon: vis.hasMoon,
        isInterior: vis.isInterior,
        isBossLevel,
        boss: spec.boss,
        objectPool: spec.objectPool,
        specialObjectPool: spec.specialObjectPool,
        characterPool: spec.characterPool,
        specialNpcPool: spec.specialNpcPool,
      });
    }
  }

  return list;
}

export const LEVELS: LevelConfig[] = buildAllLevels();

export function getLevelConfig(id: number): LevelConfig {
  return LEVELS.find((lvl) => lvl.id === id) || LEVELS[0];
}

export function getLevelsByWorld(worldId: number): LevelConfig[] {
  return LEVELS.filter((lvl) => lvl.worldId === worldId);
}
