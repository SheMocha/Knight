export function getWorldConfig(worldId: number): WorldConfig {
  return WORLDS.find((w) => w.id === worldId) || WORLDS[0];
}

export function getWorldForLevel(levelId: number): WorldConfig {
  const clamped = Math.max(1, Math.min(TOTAL_LEVELS, Math.floor(levelId)));
  const worldId = Math.ceil(clamped / LEVELS_PER_WORLD);
  return getWorldConfig(worldId);
}
